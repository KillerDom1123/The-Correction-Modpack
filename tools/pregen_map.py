def serve(args):
    """Serve the live map on this PC only. Every --interval seconds the data is read again (only what changed on the VM
    is downloaded). The open page asks every half interval, at /data?have=<version>: 204 when nothing changed, else the new
    data, which it repaints in place, keeping its zoom and position. Every response carries X-Checked (when the VM was
    last read) and, while the VM can't be read, X-Error."""
    import contextlib
    import hashlib
    import http.server
    import threading
    import urllib.parse
    import webbrowser

    lock, cache = threading.Lock(), {}
    cur = {"version": 0, "json": "", "hash": None, "checked": 0.0, "error": None}

    def refresh(quiet):
        with (contextlib.redirect_stdout(io.StringIO()) if quiet else contextlib.nullcontext()):
            data, summary = collect(args, cache)
        snap = data.pop("snapshot")
        digest = hashlib.sha1(json.dumps(data, separators=(",", ":")).encode("utf-8")).hexdigest()
        with lock:
            cur["checked"], cur["error"] = snap, None
            if digest == cur["hash"]:
                return
            version = cur["version"] + 1
        data["snapshot"] = snap
        data["live"] = {"interval": args.interval, "version": version}
        body = json.dumps(data, separators=(",", ":"))
        with lock:
            cur.update(version=version, json=body, hash=digest)
        print(f"[{time.strftime('%H:%M:%S')}] updated: {summary}")

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            url = urllib.parse.urlsplit(self.path)
            with lock:
                version, data_json, checked, error = cur["version"], cur["json"], cur["checked"], cur["error"]
            status, body, ctype = 200, b"", None
            if url.path == "/":
                body, ctype = render(data_json, False).encode("utf-8"), "text/html; charset=utf-8"
            elif url.path == "/data":
                if urllib.parse.parse_qs(url.query).get("have") == [str(version)]:
                    status = 204
                else:
                    body, ctype = data_json.encode("utf-8"), "application/json"
            else:
                self.send_error(404)
                return
            self.send_response(status)
            if ctype:
                self.send_header("Content-Type", ctype)
                self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Checked", f"{checked:.0f}")
            if error:
                self.send_header("X-Error", error)
            self.end_headers()
            if body:
                self.wfile.write(body)

        def log_message(self, *a):
            pass

    refresh(quiet=False)
    server = http.server.ThreadingHTTPServer(("127.0.0.1", args.port), Handler)  # this PC only
    threading.Thread(target=server.serve_forever, daemon=True).start()
    url = f"http://localhost:{args.port}/"
    print(f"live map at {url}: the VM is read every {args.interval} s and the page follows (Ctrl+C to stop)")
    if not args.no_browser:
        webbrowser.open(url)
    next_t = time.time()
    try:
        while True:
            next_t += args.interval
            time.sleep(max(0.5, next_t - time.time()))
            if time.time() - next_t > args.interval:  # fell behind (a slow read, or the PC slept): start counting again
                next_t = time.time()
            try:
                refresh(quiet=True)
            except Exception as e:  # the VM busy or the network down: keep serving the last map
                msg = re.sub(r"[^\x20-\x7e]", " ", f"{type(e).__name__}: {e}")[:160]
                with lock:
                    changed, cur["error"] = cur["error"] != msg, msg
                if changed:
                    print(f"[{time.strftime('%H:%M:%S')}] can't read the VM, keeping the last map: {msg}")
    except KeyboardInterrupt:
        server.shutdown()


